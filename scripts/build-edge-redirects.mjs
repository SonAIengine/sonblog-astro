import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const REDIRECTS_PATH = path.join(ROOT, "src/redirects.generated.json");
const OUTPUT_PATH = path.join(ROOT, "ops/caddy/sonblog-edge.caddy");
const CHECK_ONLY = process.argv.includes("--check");

const GITHUB_PAGES_IPS = [
  "185.199.108.153",
  "185.199.109.153",
  "185.199.110.153",
  "185.199.111.153",
];

function quote(value) {
  return JSON.stringify(value);
}

function buildConfig(redirects) {
  const entries = Object.entries(redirects).sort(([left], [right]) =>
    left.localeCompare(right, "en")
  );
  const lines = [
    "# Generated by scripts/build-edge-redirects.mjs. Do not edit manually.",
    "# The edge returns real HTTP redirects before proxying canonical pages to GitHub Pages.",
    "infoedu.co.kr {",
    "\t@compat_posts path_regexp compat_posts ^/posts/(.+)$",
    "\tredir @compat_posts /{re.compat_posts.1} 301",
    "",
  ];

  for (const [index, [source, destination]] of entries.entries()) {
    const matcher = `legacy_${String(index + 1).padStart(4, "0")}`;
    lines.push(`\t@${matcher} path ${quote(source)}`);
    lines.push(`\tredir @${matcher} ${quote(destination)} 301`);
  }

  lines.push(
    "",
    "\treverse_proxy " +
      GITHUB_PAGES_IPS.map(ip => `https://${ip}`).join(" ") +
      " {",
    "\t\theader_up Host infoedu.co.kr",
    "\t\ttransport http {",
    "\t\t\ttls_server_name infoedu.co.kr",
    "\t\t}",
    "\t}",
    "}",
    ""
  );

  return lines.join("\n");
}

const redirects = JSON.parse(fs.readFileSync(REDIRECTS_PATH, "utf8"));
const output = buildConfig(redirects);

if (CHECK_ONLY) {
  const existing = fs.existsSync(OUTPUT_PATH)
    ? fs.readFileSync(OUTPUT_PATH, "utf8")
    : "";
  if (existing !== output) {
    console.error(
      "ops/caddy/sonblog-edge.caddy is stale. Run: pnpm run edge:redirects"
    );
    process.exit(1);
  }
  console.log(
    `Edge redirect config is current (${Object.keys(redirects).length} routes).`
  );
} else {
  fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
  fs.writeFileSync(OUTPUT_PATH, output);
  console.log(
    `Wrote ${path.relative(ROOT, OUTPUT_PATH)} (${Object.keys(redirects).length} routes).`
  );
}
