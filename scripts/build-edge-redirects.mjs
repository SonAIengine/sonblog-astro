import fs from "node:fs";
import path from "node:path";
import kebabcase from "lodash.kebabcase";
import slugify from "slugify";

const ROOT = path.resolve(import.meta.dirname, "..");
const REDIRECTS_PATH = path.join(ROOT, "src/redirects.generated.json");
const EDGE_ONLY_PATH = path.join(
  ROOT,
  "ops/caddy/edge-only-redirects.generated.json"
);
const OUTPUT_PATH = path.join(ROOT, "ops/caddy/sonblog-edge.caddy");
const POSTS_PATH = path.join(ROOT, "src/content/posts");
const CHECK_ONLY = process.argv.includes("--check");
const SCHEDULED_POST_MARGIN = 15 * 60 * 1000;

const GITHUB_PAGES_IPS = [
  "185.199.108.153",
  "185.199.109.153",
  "185.199.110.153",
  "185.199.111.153",
];

function quote(value) {
  return JSON.stringify(value);
}

function postFiles(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap(entry => {
    const file = path.join(dir, entry.name);
    if (entry.isDirectory()) return postFiles(file);
    return /\.(md|mdx)$/i.test(entry.name) && !entry.name.startsWith("_")
      ? [file]
      : [];
  });
}

function routeSegment(segment) {
  return /[^\x00-\x7F]/.test(segment)
    ? kebabcase(segment)
    : slugify(segment, { lower: true });
}

function compatibilityRedirects() {
  const redirects = new Map();

  for (const file of postFiles(POSTS_PATH)) {
    const source = fs.readFileSync(file, "utf8");
    const frontmatter = source.match(/^---\r?\n([\s\S]*?)\r?\n---/)?.[1] ?? "";
    const draft = frontmatter.match(/^draft:\s*(\S+)/m)?.[1];
    const published = frontmatter.match(/^pubDatetime:\s*([^\s#]+)/m)?.[1];
    const publishedAt = new Date(published ?? "").getTime();
    if (draft === "true" || !Number.isFinite(publishedAt)) continue;
    if (Date.now() <= publishedAt - SCHEDULED_POST_MARGIN) continue;

    const relative = path
      .relative(POSTS_PATH, file)
      .split(path.sep)
      .join("/")
      .replace(/\.(md|mdx)$/i, "");
    const segments = relative.split("/").filter(segment => !segment.startsWith("_"));
    const slug = segments.pop();
    const canonical = `/${[...segments, slug].join("/")}/`;
    const compatibility = `/posts/${[...segments.map(routeSegment), slug].join("/")}/`;
    const previous = redirects.get(compatibility);
    if (previous && previous !== canonical) {
      throw new Error(`Conflicting compatibility route: ${compatibility}`);
    }
    redirects.set(compatibility, canonical);
  }

  return [...redirects.entries()].sort(([left], [right]) =>
    left.localeCompare(right, "en")
  );
}

function buildConfig(redirects, edgeOnlyRedirects, compatibilityEntries) {
  const entries = Object.entries(redirects).sort(([left], [right]) =>
    left.localeCompare(right, "en")
  );
  const edgeOnlyEntries = Object.entries(edgeOnlyRedirects).sort(
    ([left], [right]) => left.localeCompare(right, "en")
  );
  const lines = [
    "# Generated by scripts/build-edge-redirects.mjs. Do not edit manually.",
    "# The edge returns real HTTP redirects before proxying canonical pages to GitHub Pages.",
    "infoedu.co.kr {",
  ];

  for (const [index, [source, destination]] of compatibilityEntries.entries()) {
    const matcher = `compat_${String(index + 1).padStart(4, "0")}`;
    lines.push(`\t@${matcher} path ${quote(source)}`);
    lines.push(`\tredir @${matcher} ${quote(destination)} 301`);
  }

  lines.push("");

  for (const [index, [source, destination]] of entries.entries()) {
    const matcher = `legacy_${String(index + 1).padStart(4, "0")}`;
    lines.push(`\t@${matcher} path ${quote(source)}`);
    lines.push(`\tredir @${matcher} ${quote(destination)} 301`);
  }

  lines.push("");

  for (const [index, [source, destination]] of edgeOnlyEntries.entries()) {
    const matcher = `edge_${String(index + 1).padStart(4, "0")}`;
    lines.push(`\t@${matcher} path ${quote(source)}`);
    lines.push(`\tredir @${matcher} ${quote(destination)} 301`);
  }

  lines.push(
    "",
    "\treverse_proxy " +
      GITHUB_PAGES_IPS.map(ip => `https://${ip}`).join(" ") +
      " {",
    "\t\theader_up Host infoedu.co.kr",
    "\t\ttransport http {",
    "\t\t\ttls_server_name infoedu.co.kr",
    "\t\t}",
    "\t}",
    "}",
    ""
  );

  return lines.join("\n");
}

const redirects = JSON.parse(fs.readFileSync(REDIRECTS_PATH, "utf8"));
const edgeOnlyRedirects = JSON.parse(fs.readFileSync(EDGE_ONLY_PATH, "utf8"));
for (const source of Object.keys(edgeOnlyRedirects)) {
  if (source in redirects) {
    throw new Error(`Edge-only redirect duplicates a static route: ${source}`);
  }
}
const compatibilityEntries = compatibilityRedirects();
const output = buildConfig(redirects, edgeOnlyRedirects, compatibilityEntries);

if (CHECK_ONLY) {
  const existing = fs.existsSync(OUTPUT_PATH)
    ? fs.readFileSync(OUTPUT_PATH, "utf8")
    : "";
  if (existing !== output) {
    console.error(
      "ops/caddy/sonblog-edge.caddy is stale. Run: pnpm run edge:redirects"
    );
    process.exit(1);
  }
  console.log(
    `Edge redirect config is current (${compatibilityEntries.length} compatibility, ${Object.keys(redirects).length} legacy, ${Object.keys(edgeOnlyRedirects).length} edge-only routes).`
  );
} else {
  fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
  fs.writeFileSync(OUTPUT_PATH, output);
  console.log(
    `Wrote ${path.relative(ROOT, OUTPUT_PATH)} (${compatibilityEntries.length} compatibility, ${Object.keys(redirects).length} legacy, ${Object.keys(edgeOnlyRedirects).length} edge-only routes).`
  );
}
